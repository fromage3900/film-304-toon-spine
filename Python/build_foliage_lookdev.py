NAME = "L_Foliage_Lookdev"
MAP_DIR = "/Game/Maps"
MESH_DIR = "/Game/Meshes/Foliage"
PNG_STAGING = Path(__file__).resolve().parents[1] / "Saved" / "GeneratedMeshes"

CARD_SIZE = 130.0          # uu, square card
ENGINE_SHAPES = {
    "plane": "/Engine/BasicShapes/Plane.Plane",
    "cube": "/Engine/BasicShapes/Cube.Cube",
}
INSTANCES = {
    "fern": "/Game/Materials/Instances/MI_Foliage_Fern",
    "hedge": "/Game/Materials/Instances/MI_Foliage_Hedge",
}
SUN_ROT = (-38.0, 210.0, 0.0)      # (pitch, yaw, roll) - see build_gouache_lookdev
SUN_INTENSITY = 3.2
SKY_INTENSITY = 0.9
CAM_LOC = (340.0, -420.0, 160.0)
CAM_LOOK_AT = (0.0, 0.0, 70.0)


# ---------------------------------------------------------------------------
# OBJ generation - cards in XZ plane (vertical), normal +Y, units = uu
# ---------------------------------------------------------------------------

def _quad_verts(size: float, cx: float = 0.0, cz: float = 0.0):
    """A square quad's corners, centred at (cx, cz), 0.5*size half-extent."""
    h = size / 2.0
    return [(cx - h, 0.0, cz - h), (cx + h, 0.0, cz - h),
            (cx + h, 0.0, cz + h), (cx - h, 0.0, cz + h)]


def gen_card_obj(kind: str, out_path: Path) -> dict:
    """Write one card mesh as OBJ. Returns {verts, tris} for the report.

    Topologies:
      quad   - one card at origin
      cross  - two cards, second rotated 90 degrees about Y (vertical axis)
      fan    - three cards rotated -55/0/+55 degrees, base-anchored
    """
    verts, normals, uvs, faces = [], [], [], []

    def emit_quad(corners, nrm):
        base = len(verts)
        for (x, y, z) in corners:
            verts.append((x, y, z))
            normals.append(nrm)
        uvs.extend([(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)])
        faces.append((base + 1, base + 2, base + 3))
        faces.append((base + 1, base + 3, base + 4))

    def rot_y(pts, deg, cx=0.0, cz=CARD_SIZE / 2.0):
        a = math.radians(deg)
        c, s = math.cos(a), math.sin(a)
        out = []
        for (x, y, z) in pts:
            dx, dz = x - cx, z - cz
            out.append((cx + dx * c + dz * s, y, cz - dx * s + dz * c))
        return out

    if kind == "quad":
        emit_quad(_quad_verts(CARD_SIZE), (0.0, -1.0, 0.0))
    elif kind == "cross":
        q = _quad_verts(CARD_SIZE)
        emit_quad(q, (0.0, -1.0, 0.0))
        emit_quad(rot_y(q, 90.0), (1.0, 0.0, 0.0))
    elif kind == "fan":
        for deg in (-55.0, 0.0, 55.0):
            emit_quad(rot_y(_quad_verts(CARD_SIZE), deg),
                      (math.sin(math.radians(deg)), -math.cos(math.radians(deg)),
                       0.0))
    else:
        raise ValueError(f"unknown card topology {kind!r}")

    lines = ["# generated by build_foliage_lookdev.py - do not hand-edit"]
    for (x, y, z) in verts:
        lines.append(f"v {x:.3f} {y:.3f} {z:.3f}")
    for (x, y, z) in normals:
        lines.append(f"vn {x:.3f} {y:.3f} {z:.3f}")
    for (u, v) in uvs:
        lines.append(f"vt {u:.4f} {v:.4f}")
    for (a, b, c) in faces:
        lines.append(f"f {a}/{a} {b}/{b} {c}/{c}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="ascii")
    return {"verts": len(verts), "tris": len(faces)}


CARDS = (
    ("SM_Foliage_CardQuad", "quad"),
    ("SM_Foliage_CardCross", "cross"),
    ("SM_Foliage_CardFan", "fan"),
)


def import_cards() -> dict:
    """Generate + import the three card meshes. Returns path/asset info."""
    lib.ensure_dir(MESH_DIR)
    tasks = []
    made = {}
    for name, kind in CARDS:
        obj = PNG_STAGING / f"{name}.obj"
        stats = gen_card_obj(kind, obj)
        task = unreal.AssetImportTask()
        task.filename = str(obj)
        task.destination_path = MESH_DIR
        task.destination_name = name
        task.automated = True
        task.save = True
        task.replace_existing = True
        tasks.append(task)
        made[name] = stats
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)
    for name in made:
        asset = unreal.load_asset(f"{MESH_DIR}/{name}.{name}")
        made[name]["imported"] = asset is not None
        lib.log(f"CARD {name}: {made[name]} ")
    return made


