def resolve_world_factory():
    for nm in ("WorldFactory", "WorldFactoryNew", "WorldFactoryNewLevel"):
        cls = getattr(unreal, nm, None)
        if cls is not None:
            return cls
    return None


def ensure_level() -> str:
    """Open the fixture level via lookdev_lib (phantom purge, create, save,
    then load) - see lookdev_lib.ensure_level for why this is shared."""
    status = lookdev_lib.ensure_level(NAME)
    lib.log(f"level {NAME}: {' '.join(status['actions'])}")
    return status["asset_path"]


def spawn_mesh(label, mesh_path, location, scale, material, yaw=0.0,
               pitch=0.0):
    mesh = unreal.load_asset(mesh_path)
    if mesh is None:
        lib.log(f"WARN {label}: mesh missing {mesh_path}")
        return None
    actor = unreal.EditorLevelLibrary.spawn_actor_from_class(
        unreal.StaticMeshActor, unreal.Vector(*location),
        unreal.Rotator(roll=0.0, pitch=float(pitch), yaw=float(yaw)))
    actor.set_actor_label(label)
    comp = actor.get_component_by_class(unreal.StaticMeshComponent)
    comp.set_mobility(unreal.ComponentMobility.MOVABLE)
    comp.set_static_mesh(mesh)
    if scale != 1.0:
        actor.set_actor_scale3d(unreal.Vector(scale, scale, scale))
    if material is not None:
        comp.set_material(0, material)
    comp.set_mobility(unreal.ComponentMobility.STATIC)
    return actor


def spawn_ground():
    return spawn_mesh("FLD_Ground", ENGINE_SHAPES["plane"], (0, 0, 0), 14.0,
                      None)


def spawn_lights():
    pitch, yaw, roll = SUN_ROT
    sun = unreal.EditorLevelLibrary.spawn_actor_from_class(
        unreal.DirectionalLight, unreal.Vector(0, 0, 4000),
        unreal.Rotator(roll=float(roll), pitch=float(pitch), yaw=float(yaw)))
    sun.set_actor_label("FLD_Sun")
    try:
        c = sun.get_component_by_class(unreal.DirectionalLightComponent)
        c.set_mobility(unreal.ComponentMobility.MOVABLE)
        c.set_intensity(SUN_INTENSITY)
        c.set_mobility(unreal.ComponentMobility.STATIC)
    except Exception as exc:
        lib.log(f"WARN sun config: {str(exc)[:100]}")
    sky = unreal.EditorLevelLibrary.spawn_actor_from_class(
        unreal.SkyLight, unreal.Vector(0, 0, 1000))
    sky.set_actor_label("FLD_Sky")
    try:
        c = sky.get_component_by_class(unreal.SkyLightComponent)
        c.set_mobility(unreal.ComponentMobility.MOVABLE)
        c.set_intensity(SKY_INTENSITY)
        c.set_mobility(unreal.ComponentMobility.STATIC)
    except Exception as exc:
        lib.log(f"WARN sky config: {str(exc)[:100]}")
    return sun, sky


def spawn_camera():
    cam = unreal.EditorLevelLibrary.spawn_actor_from_class(
        unreal.CineCameraActor, unreal.Vector(*CAM_LOC),
        unreal.Rotator(0, 0, 0))
    cam.set_actor_label("FLD_Cam")
    try:
        comp = cam.get_component_by_class(unreal.CineCameraComponent)
        lib.try_set(comp, "current_focal_length", 55.0)
    except Exception as exc:
        lib.log(f"WARN camera focal: {str(exc)[:100]}")
    try:
        rot = unreal.KismetMathLibrary.find_look_at_rotation(
            unreal.Vector(*CAM_LOC), unreal.Vector(*CAM_LOOK_AT))
        cam.set_actor_rotation(rot)
    except Exception as exc:
        lib.log(f"WARN camera aim: {str(exc)[:100]}")
    return cam


# label, card, instance, loc, yaw, pitch
CARDS_IN_SCENE = (
    ("FLD_Fern_Quad",  "SM_Foliage_CardQuad",  "fern",  (-160, 40, 65),  12.0, 0.0),
    ("FLD_Fern_Cross", "SM_Foliage_CardCross", "fern",  (-40, -60, 65),  -25.0, 0.0),
    ("FLD_Hedge_Cross","SM_Foliage_CardCross", "hedge", (90, 50, 65),    40.0, 0.0),
    ("FLD_Hedge_Fan",  "SM_Foliage_CardFan",   "hedge", (230, -30, 65),  -12.0, 0.0),
    ("FLD_Fan_Tilted", "SM_Foliage_CardFan",   "fern",  (60, 140, 65),   150.0, -14.0),
)


def build() -> dict:
    lib.log(f"=== {NAME} ===")
    report = {"level": NAME, "errors": [], "warnings": [],
              "cards": {}, "scene": [], "materials": {}}

    cards = import_cards()
    report["cards"] = {k: v for k, v in cards.items()}
    missing = [k for k, v in cards.items() if not v.get("imported")]
    if missing:
        report["errors"].append(f"card import failed: {missing}")

    mats = {}
    for key, path in INSTANCES.items():
        asset = unreal.load_asset(path)
        mats[key] = {"path": path, "loaded": asset is not None}
        if asset is None:
            report["warnings"].append(f"{key}: instance missing {path}")

    path = ensure_level()
    report["level_asset"] = path

    spawn_ground()
    for label, card, inst_key, loc, yaw, pitch in CARDS_IN_SCENE:
        mat = unreal.load_asset(INSTANCES[inst_key])
        ok = spawn_mesh(label, f"{MESH_DIR}/{card}.{card}", loc, 1.0, mat,
                        yaw=yaw, pitch=pitch) is not None
        report["scene"].append({"label": label, "card": card,
                                "instance": inst_key, "spawned": ok})
        if not ok:
            report["errors"].append(f"{label}: spawn failed")

    spawn_lights()
    spawn_camera()

    saved = lookdev_lib.save_current_level(report["level_asset"])
    report["level_saved"] = saved

    actors = unreal.EditorLevelLibrary.get_all_level_actors() or []
    labels = [a.get_actor_label() for a in actors]
    report["census"] = {
        "total": len(actors),
        "static_mesh": len([a for a in actors
                            if isinstance(a, unreal.StaticMeshActor)]),
        "all_cards_present": all(r["label"] in labels
                                 for r in report["scene"]),
    }

    report["notes"] = {
        "sway": ("SwayAmount/SwaySpeed/SwayPhase are instance-level on "
                 "MI_Foliage_*/the master; sway is a WPO term, so stills "
                 "prove the mask and shading only - motion needs PIE."),
        "silhouette_is_mask": (
            "The cards are plain quads; the silhouette is T_SDF_Leaf cut by "
            "MaskCutoff/MaskSharpness. A ragged edge here is a mask/opacity "
            "problem, never a mesh problem."),
        "two_sided": ("The master is two-sided; the cross/fan topologies "
                      "exist precisely to expose back-face shading."),
    }
    report["ok"] = (not report["errors"]) and saved
    _write_report(report)
    lib.log(f"{NAME}: ok={report['ok']} cards={len(report['scene'])} "
            f"saved={saved}")
    return report


def _write_report(report: dict) -> None:
    """Persist the fixture's evidence next to the other Audit reports.

    The driver (Tools/build_lookdev_levels.py) gates on the .umap file, but a
    level existing is not the same as the level containing the right actors -
    this report is the census that closes that gap.
    """
    import json
    out = (Path(__file__).resolve().parents[1] / "Saved" / "Audit"
           / "foliage_lookdev_report.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")


def main() -> int:
    return 0 if build()["ok"] else 1


if __name__ == "__main__":
    import sys
    sys.exit(main())
