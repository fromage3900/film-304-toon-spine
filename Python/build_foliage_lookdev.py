"""Build L_Foliage_Lookdev - the controlled fixture for the foliage master.

WHY CARDS ARE GENERATED HERE
-----------------------------
The foliage master (M_Master_Toon_Foliage) is masked + two-sided + swaying,
and before this builder it had no geometry to sit on. Foliage cards are the
classical fixture: a vertical quad, alpha-cut by the cover SDF (T_SDF_Leaf),
fanned/crossed into clusters. The meshes are generated as OBJ from pure
stdlib - the same "values ported, pixels/geometry regenerated" contract the
textures use - and imported through Interchange.

The card is a PLAIN quad on purpose: the silhouette is the opacity mask's
job, not the mesh's. Three topologies cover the cases:
  card_quad   - one quad; terminator + mask read with zero occlusion noise
  card_cross  - two quads at 90 degrees; the classic bush/tuft read, and the
                first place two-sided shading contradicts itself
  card_fan    - three quads fanned at -55/0/+55 degrees; depth stacking and
                the sway response at clustered scale

Each card instance gets one of the foliage instances (Fern/Hedge) so the
fixture judges the INSTANCED look, not the bare master.
"""
from __future__ import annotations

