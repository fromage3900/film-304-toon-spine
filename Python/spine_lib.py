def _pin_names(dst):
    """Ordered input pin names of `dst` as THIS build's binder expects them."""
    try:
        return [str(p) for p in
                unreal.MaterialEditingLibrary
                .get_material_expression_input_names(dst)]
    except Exception:
        return []


def _resolve_pin(dst, wanted):
    """Match a wanted pin name against the node's real pins.

    The binder matches by exact display name, and this build's names are not
    guessable: Power exposes Base/Exp (not A/B), Length has ONE unnamed pin,
    If spells its result pins 'A > B' with spaces. Guessing produced silent
    no-ops and a master that fell back to the default material. Probe first,
    guess last.
    """
    pins = _pin_names(dst)
    if not pins:
        return wanted
    norm = lambda s: s.replace(" ", "").lower()
    for p in pins:
        if norm(p) == norm(wanted):
            return p
    return wanted


def connect(src, src_output, dst, dst_input):
    """Connect, trying a list of candidate pin names.

    UE 5.8 exposes 'True'/'False' on StaticSwitchParameter (not A/B), 'Base'/
    'Exp' on Power (not A/B), and an unnamed single pin on Length. Returns True
    on first success.
    """
    lib = unreal.MaterialEditingLibrary
    if src_output is None:
        src_output = ""
    if isinstance(dst_input, (list, tuple)):
        for pin in dst_input:
            try:
                if lib.connect_material_expressions(src, src_output, dst,
                                                    _resolve_pin(dst, pin)) \
                        is not False:
                    return True
            except Exception:
                continue
        return False
    try:
        return lib.connect_material_expressions(src, src_output, dst,
                                               _resolve_pin(dst, dst_input)) \
            is not False
    except Exception:
        return False


def length2(fn, a, b, x=0, y=0):
    """Length of a 2D pair built from two scalars.

    Length exposes ONE unnamed input on this build ('' connects, 'A'/'B' do
    not), so scalar pairs must go through AppendVector - the same lesson the
    Voronoi feature-point path already learned.
    """
    pair = expr(fn, unreal.MaterialExpressionAppendVector, x, y)
    connect(a, "", pair, ["A", "a"])
    connect(b, "", pair, ["B", "b"])
    ln = expr(fn, unreal.MaterialExpressionLength, x + 160, y)
    connect(pair, "", ln, ["", "None"])
    return ln


def unary(src, dst):
    """Wire a single-input node (Abs, Saturate, OneMinus, Frac, Sine, ...).

    FIX 2026-10-03 - a silent-success bug that shipped a broken material.
    MaterialEditingLibrary.get_material_expression_input_names() returns the
    Python string "None" (not an empty string) for the unnamed input of
    Saturate and OneMinus on UE 5.8:

        MaterialExpressionSaturate  input_names == ["None"]
        MaterialExpressionOneMinus  input_names == ["None"]

    Connect() then resolves the literal name "None", which UE accepts and
    silently treats as an UNSET pin, so connect() returned True while nothing
    was wired. The material compiled to "(Node Saturate) Missing Saturate
    input" and rendered as Default Material, with verify_material and the
    dead-node census both reporting clean.

    Measured pin names (Saved/Audit/pin_name_probe.json):
        Saturate / OneMinus  -> "None"   (the literal, must be normalised)
        Normalize            -> "VectorInput"
        SmoothStep           -> Min, Max, Value
        LinearInterpolate    -> A, B, Alpha
        Multiply / Add / Sub -> A, B

    A "None" pin name is normalised to the empty pin, which is what an unnamed
    input actually is. Return value is still not trusted by callers that need
    certainty - see connect() - but it now reflects reality.
    """
    lib = unreal.MaterialEditingLibrary
    try:
        pins = [str(p) for p in lib.get_material_expression_input_names(dst)]
    except Exception:
        pins = []
    # "None" is a genuine UE artefact for unnamed pins, not a missing value.
    # Leave "" alone - that IS the unnamed pin and connect() handles it.
    pins = ["" if p == "None" else p for p in pins]
    candidates = pins + ["Input", "input", "VectorInput", ""]
    for pin in candidates:
        if connect(src, "", dst, pin):
            return True
    # last resort: the node's own input property
    for prop in ("input", "Input"):
        try:
            dst.get_editor_property(prop).connect(0, src)
            return True
        except Exception:
            continue
    log(f"WARN unary failed to wire {type(dst).__name__}: no pin accepted "
        f"the connection (tried {candidates})")
    return False


def binary(a, b, dst):
    """Wire A/B on a two-input math node, using the node's REAL pin names.

    Most math nodes are A/B, but Power is Base/Exp on this build - probing the
    names first is what makes one helper correct for both.
    """
    pins = _pin_names(dst) or ["A", "B"]
    ok_a = connect(a, "", dst, [pins[0], "A", "a", "Input0"])
    ok_b = connect(b, "", dst, [pins[1] if len(pins) > 1 else "B",
                                "B", "b", "Input1"])
    return ok_a and ok_b


def ternary(a, b, c, dst):
    """Wire three inputs (Lerp: A/B/Alpha) using the node's REAL pin names."""
    pins = _pin_names(dst) or ["A", "B", "Alpha"]
    ok_a = connect(a, "", dst, [pins[0], "A", "a"])
    ok_b = connect(b, "", dst, [pins[1] if len(pins) > 1 else "B", "B", "b"])
    ok_c = connect(c, "", dst, [pins[2] if len(pins) > 2 else "Alpha",
                                "Alpha", "C", "c"])
    return ok_a and ok_b and ok_c


def connect_property(src, material_property, src_output=""):
    unreal.MaterialEditingLibrary.connect_material_property(
        src, src_output, material_property)


