def expr(owner, cls, x=0, y=0):
    """Create an expression inside a Material or a MaterialFunction."""
    if isinstance(owner, unreal.MaterialFunction):
        return unreal.MaterialEditingLibrary.create_material_expression_in_function(
            owner, cls, x, y)
    return unreal.MaterialEditingLibrary.create_material_expression(owner, cls, x, y)


def scalar(owner, name, group, default, x=0, y=0, desc=None):
    e = expr(owner, unreal.MaterialExpressionScalarParameter, x, y)
    e.set_editor_property("parameter_name", name)
    e.set_editor_property("group", group)
    e.set_editor_property("default_value", float(default))
    _desc(e, desc)
    return e


def vector(owner, name, group, default, x=0, y=0, desc=None):
    e = expr(owner, unreal.MaterialExpressionVectorParameter, x, y)
    e.set_editor_property("parameter_name", name)
    e.set_editor_property("group", group)
    e.set_editor_property("default_value", unreal.LinearColor(*default))
    _desc(e, desc)
    return e


def constant(owner, rgb, x=0, y=0):
    e = expr(owner, unreal.MaterialExpressionConstant3Vector, x, y)
    e.set_editor_property("constant", unreal.LinearColor(*rgb))
    return e


def scalar_const(owner, v, x=0, y=0):
    e = expr(owner, unreal.MaterialExpressionConstant, x, y)
    e.set_editor_property("r", float(v))
    return e


def texture_param(owner, name, group, x=0, y=0, desc=None):
    """Texture parameter. Never auto-assigns a texture: an unwired parameter
    samples the default grey, which is a safe placeholder and keeps the material
    free of banned /Engine/ content (see material_lib.BANNED_TEXTURE_PATHS)."""
    e = expr(owner, unreal.MaterialExpressionTextureSampleParameter2D, x, y)
    e.set_editor_property("parameter_name", name)
    e.set_editor_property("group", group)
    _desc(e, desc)
    return e


def _desc(e, text):
    if not text:
        return
    for prop in ("desc", "parameter_desc", "Desc"):
        try:
            if e.has_editor_property(prop):
                e.set_editor_property(prop, text)
                return
        except Exception:
            continue


