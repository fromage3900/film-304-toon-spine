def add_function_input(fn, name, input_type, preview=(0.0, 0.0, 0.0, 0.0), x=-800, y=0):
    """Add a FunctionInput to a MaterialFunction and return it.

    input_type is an unreal.FunctionInputType scalar, e.g.
        unreal.FunctionInputType.FUNCTION_INPUT_SCALAR
    """
    e = expr(fn, unreal.MaterialExpressionFunctionInput, x, y)
    e.set_editor_property("input_name", name)
    try:
        e.set_editor_property("input_type", input_type)
    except Exception as exc:
        log(f"add_function_input {name}: input_type set failed ({exc})")
    try:
        e.set_editor_property("preview_value", unreal.Vector4(*preview))
    except Exception:
        pass
    return e


def add_function_output(fn, name, x=800, y=0):
    """Add a FunctionOutput.

    UE 5.8 has NO FunctionOutputType enum and no output_type/material_property
    field on MaterialExpressionFunctionOutput - verified by probing a real
    function (MF_ColorRamp3) on 2026-09-30. The output type is inferred from
    what is wired into it. Only output_name and desc are settable.
    """
    e = expr(fn, unreal.MaterialExpressionFunctionOutput, x, y)
    e.set_editor_property("output_name", name)
    return e


