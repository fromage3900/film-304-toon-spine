MATERIALS_ROOT = "/Game/Materials"
MASTER_DIR = f"{MATERIALS_ROOT}/Masters"
FUNCTION_DIR = f"{MATERIALS_ROOT}/Functions"
PROFILE_DIR = f"{MATERIALS_ROOT}/ToonProfiles"

REPORT = Path(os.environ.get("TEMP", ".")) / "spine_build_report.json"


def log(m):
    unreal.log("[SpineBuild] " + str(m))


