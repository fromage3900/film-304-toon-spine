"""Shared helpers for building the 304 film toon spine from code.

Every material and material function in this project is GENERATED by a script,
never copied as a .uasset. That is deliberate:

  * a binary blob cannot be reviewed in a pull request
  * a .uasset moved between projects keeps its old package path and breaks
  * UE 5.8 silently drops a material graph on a second cross-project rename
    (observed 2026-09-29: 751,265 -> 666,458 bytes, all 10 MaterialFunctionCall
    references gone, verify reported clean:true because it counted zero calls)

Generated content means a group member can regenerate the spine on any UE 5.8
checkout instead of receiving a file nobody can edit.

Run headless:
    UnrealEditor-Cmd.exe <project>.uproject ^
      -ExecutePythonScript="Python/build_spine.py" -stdout -unattended

Assert on the report FILE, not the log - unreal.log() is unreliable under
-stdout capture.
"""
from __future__ import annotations

import json
import os
