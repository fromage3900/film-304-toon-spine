def function_calls(material):
    """Every MaterialFunctionCall path in a material graph."""
    lib = unreal.MaterialEditingLibrary
    out = []
    for e in lib.get_material_expressions(material) or []:
        if e is not None and type(e).__name__ == "MaterialExpressionMaterialFunctionCall":
            try:
                mf = e.get_editor_property("material_function")
                if mf:
                    out.append(mf.get_path_name())
            except Exception:
                pass
    return out


def expression_count(material):
    lib = unreal.MaterialEditingLibrary
    try:
        return len(list(lib.get_material_expressions(material) or []))
    except Exception:
        return 0


def function_expression_count(fn):
    """Expressions inside a MaterialFunction (get_material_expressions is
    Material-only in UE 5.8)."""
    lib = unreal.MaterialEditingLibrary
    try:
        return len(list(lib.get_material_function_expressions(fn) or []))
    except Exception:
        return 0


def verify_function(name, min_expressions=15, expect_underscore_output=True):
    """Assert a generated MaterialFunction actually contains a graph."""
    path = asset_path(FUNCTION_DIR, name)
    fn = unreal.load_asset(path)
    result = {"path": path, "loads": fn is not None, "ok": False}

    if fn is None:
        log(f"VERIFY FAIL {name}: does not load")
        return result

    n = function_expression_count(fn)
    result["expression_count"] = n

    if n == 0:
        result["error"] = "ZERO expressions - function is empty, not verified"
    elif n < min_expressions:
        result["error"] = f"only {n} expressions (expected >= {min_expressions})"

    result["ok"] = not result.get("error")
    log(f"VERIFY {name}: ok={result['ok']} exprs={n} {result.get('error', '')}")
    return result


def verify_material(name, expected_calls, min_expressions=10):
    """Assert a generated material is real.

    Guards against the zero-node false pass: a material that reports 0 function
    calls is NOT verified, it is empty.
    """
    path = asset_path(MASTER_DIR, name)
    mat = unreal.load_asset(path)
    result = {"path": path, "loads": mat is not None, "ok": False}

    if mat is None:
        log(f"VERIFY FAIL {name}: does not load")
        return result

    calls = sorted({c.rsplit("/", 1)[-1].split(".", 1)[0] for c in function_calls(mat)})
    nexpr = expression_count(mat)

    result["mf_calls"] = calls
    result["expression_count"] = nexpr

    missing = [c for c in expected_calls if c not in calls]
    result["missing_calls"] = missing

    # Toon Profile binding, added 2026-10-02. A material can pass every check
    # above and still be shading on ENGINE DEFAULTS: the profile is a property
    # of the SubstrateToonBSDF node, not of the material, so an unbound profile
    # leaves the graph structurally perfect and artistically inert. That is
    # exactly the state this repo shipped in until 2026-10-02 - 19 TP_* assets,
    # zero bound.
    if name == "M_Master_Toon_Universal":
        profile = None
        try:
            for n in unreal.MaterialEditingLibrary.get_material_expressions(mat) or []:
                if type(n).__name__ == "MaterialExpressionSubstrateToonBSDF":
                    profile = n.get_editor_property("toon_profile")
                    break
        except Exception as exc:
            result["toon_profile_error"] = str(exc)[:120]
        result["toon_profile"] = profile.get_name() if profile else None
        if profile is None:
            result["error"] = (result.get("error", "")
                               + " | NO Toon Profile bound to the Substrate "
                                 "Toon BSDF - renders on engine defaults")

    # a zero-count graph is empty, not clean
    if len(expected_calls) > 0 and len(calls) == 0:
        result["error"] = "ZERO function calls - graph is empty, not verified"
    elif missing:
        result["error"] = f"missing calls: {missing}"
    elif nexpr < min_expressions:
        result["error"] = f"only {nexpr} expressions (expected >= {min_expressions})"
    elif result.get("error"):
        pass  # keep the earlier profile error

    result["ok"] = not result.get("error")
    log(f"VERIFY {name}: ok={result['ok']} calls={len(calls)} exprs={nexpr} "
        f"profile={result.get('toon_profile')} {result.get('error', '')}")
    return result


